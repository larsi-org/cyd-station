// A curated 5-root CA bundle for verifying larsi.org's TLS certificate, instead of pinning to
// one specific root the way this library used to (see git history for the single-cert version).
// A single pinned root breaks the instant larsi.org's certificate provider changes; this bundle
// covers the provider Lars is on today plus the ones he'd realistically end up on if that
// changes, at a cost of a few KB instead of the ~55KB+71KB (data+code) a full public-CA-store
// bundle would cost -- see the sensor-node repo's CLAUDE.md for the flash-budget experiment that
// ruled the full-store approach out.
//
// Picked from W3Techs' SSL Certificate Authority market share (w3techs.com/technologies/
// overview/ssl_certificate, ~94% of the web combined as of 2026-07-31) plus the two CAs actually
// relevant to larsi.org specifically:
//   - ISRG Root X1 (Let's Encrypt, 64.7% of the web) -- the CA Lars actually wants to switch to;
//     GoDaddy's control panel makes that annoyingly hard to do on purpose (they'd rather sell
//     their own cert product), so this is here for whenever that finally happens.
//   - GlobalSign Root R46 (GlobalSign, 19.6%) -- the newer, longer-lived (exp. 2046) GlobalSign
//     root, not the older R3 (exp. 2029, too close for comfort in a bundle meant to sit
//     unattended on deployed hardware for years).
//   - USERTrust RSA Certification Authority (Sectigo, 4.9%) -- what most real-world Sectigo/
//     Comodo-issued certs still chain to, not their newer standalone Sectigo-branded roots.
//   - Go Daddy Root Certificate Authority - G2 (GoDaddy Group, 3.5%) -- larsi.org's current
//     provider. Same cert this library used to pin outright.
//   - DigiCert Global Root G2 (DigiCert Group, 1.6% by this survey's website-count methodology,
//     though DigiCert is actually the largest CA by revenue -- enterprise OV/EV/private-PKI
//     contracts don't show up in a public site-crawl survey).
//
// If flash pressure ever forces trimming this bundle back down, remove in this order (least
// essential first; see CLAUDE.md for a pointer back to this list):
//   1. DigiCert Global Root G2 (smallest realistic chance of ever being larsi.org's actual CA)
//   2. USERTrust RSA Certification Authority (Sectigo)
//   3. GlobalSign Root R46 (large by share, but that share is mostly reseller/hosting
//      white-labeling, not a CA Lars would deliberately pick)
//   4. Go Daddy Root Certificate Authority - G2 -- but only once larsi.org has actually migrated
//      off GoDaddy; until then this one's still load-bearing for every device in the field.
//   5. ISRG Root X1 (Let's Encrypt) -- drop last. Once larsi.org actually migrates to Let's
//      Encrypt, GoDaddy becomes droppable instead and this one becomes the new load-bearing
//      entry -- re-evaluate the whole bundle then, don't just mechanically apply this list.
//
